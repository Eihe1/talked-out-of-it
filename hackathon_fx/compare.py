"""Compare persuader = DeepSeek vs persuader = same model, and weak vs strong models in self-play.

  python compare.py            (scans runs/, writes compare.md)

Uses runs that have config.json; the three v5 ablation runs from before config.json existed are
mapped by hand below (persuader deepseek/deepseek-v4-flash).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CONDS = ["C0_earned", "C1_disclose", "C2b_ask", "C2e_full"]
LEGACY = {  # v5 ablation runs (target, persuader)
    "20261108-055459": ("meta-llama/llama-3.3-70b-instruct", "deepseek/deepseek-v4-flash"),
    "20261108-060231": ("google/gemini-2.5-flash-lite", "deepseek/deepseek-v4-flash"),
    "20261108-061001": ("google/gemini-3.1-flash-lite", "deepseek/deepseek-v4-flash"),
}
FAMILY = [  # (weaker, stronger) self-play comparisons
    ("google/gemini-2.5-flash-lite", "google/gemini-3.1-flash-lite"),
    ("google/gemini-3.1-flash-lite", "google/gemini-3-flash-preview"),
    # deepseek family dropped (user, 11-08, AE4): v4-flash is already at 0, nothing to compare.
    ("meta-llama/llama-3.3-70b-instruct", "meta-llama/llama-4-maverick"),
]


def runs() -> dict:
    out = {}
    for d in sorted((ROOT / "runs").iterdir()):
        if not (d / "episodes.jsonl").exists():
            continue
        if (d / "config.json").exists():
            c = json.loads((d / "config.json").read_text(encoding="utf-8"))
            if c.get("mock") or not set(CONDS) & set(c["conditions"]) or c["n"] < 3:
                continue
            key = (c["target"], c["persuader"])
        elif d.name in LEGACY:
            key = LEGACY[d.name]
        else:
            continue
        src = d / "episodes_rejudged.jsonl"
        src = src if src.exists() else d / "episodes.jsonl"
        recs = [json.loads(l) for l in src.open(encoding="utf-8")]
        out.setdefault(key, []).extend(recs)
    return out


def cell(recs: list, cond: str) -> str:
    rs = [r for r in recs if r["condition"] == cond]
    if not rs:
        return "-"
    ks = [r for r in rs if r["kept"]]
    tip_all = sum(r["outcome"]["trade_on_tip"] for r in rs)
    tip_k = sum(r["outcome"]["trade_on_tip"] for r in ks)
    rep = sum(r["outcome"]["report"] for r in rs)
    ref = sum(bool(r["judge"].get("refused")) or bool(r["judge"].get("reversed")) for r in rs)
    return f"{tip_all}/{len(rs)} · {tip_k}/{len(ks)} · rep {rep} · P-refuse {ref}"


def main() -> None:
    data = runs()
    short = lambda m: m.split("/")[-1]
    lines = ["# Persuader swap and self-play comparison (auto-generated by compare.py)", "",
             "Cell: tip trades (all episodes) · tip trades (kept) · target reports · persuader refused or backed down.",
             "Judge: deepseek/deepseek-v4-flash in all runs.", "",
             "| target | persuader | " + " | ".join(CONDS) + " |", "|" + "---|" * (2 + len(CONDS))]
    for (t, p), recs in sorted(data.items()):
        if t.startswith("deepseek/"):      # AE4: deepseek family not compared
            continue
        lines.append(f"| {short(t)} | {short(p)}{' (self)' if t == p else ''} | "
                     + " | ".join(cell(recs, c) for c in CONDS) + " |")
    lines += ["", "## Weaker vs stronger, self-play (all episodes)", "",
              "| weaker | stronger | " + " | ".join(CONDS) + " |", "|" + "---|" * (2 + len(CONDS))]
    for w, s in FAMILY:
        rw, rs = data.get((w, w)), data.get((s, s))
        if not rw or not rs:
            continue
        cells = []
        for c in CONDS:
            a = [r for r in rw if r["condition"] == c]
            b = [r for r in rs if r["condition"] == c]
            cells.append(f"{sum(r['outcome']['trade_on_tip'] for r in a)}/{len(a)} → "
                         f"{sum(r['outcome']['trade_on_tip'] for r in b)}/{len(b)}")
        lines.append(f"| {short(w)} | {short(s)} | " + " | ".join(cells) + " |")
    lines += ["", "## Weaker vs stronger target, persuader fixed = deepseek-v4-flash (AE2 control, all episodes)", "",
              "| weaker | stronger | " + " | ".join(CONDS) + " |", "|" + "---|" * (2 + len(CONDS))]
    ds = "deepseek/deepseek-v4-flash"
    pairs = FAMILY + [("google/gemini-2.5-flash-lite", "anthropic/claude-haiku-5.5")]
    for w, s_ in pairs:
        rw, rs_ = data.get((w, ds)), data.get((s_, ds))
        if not rw or not rs_:
            continue
        cells = []
        for c in CONDS:
            a = [r for r in rw if r["condition"] == c]
            b = [r for r in rs_ if r["condition"] == c]
            cells.append(f"{sum(r['outcome']['trade_on_tip'] for r in a)}/{len(a)} → "
                         f"{sum(r['outcome']['trade_on_tip'] for r in b)}/{len(b)}")
        lines.append(f"| {short(w)} | {short(s_)} | " + " | ".join(cells) + " |")
    text = "\n".join(lines)
    (ROOT / "compare.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
