"""Summarise ablation runs: per model x condition, all episodes and kept episodes.

  python analyze.py runs/<dir1> runs/<dir2> ...      (writes analysis.md next to this file)

Rates come with Wilson 95% intervals. Fisher exact tests compare each condition with C1_disclose
and with C0_earned on tip trades (kept episodes). Exploratory: no multiple-comparison correction.
"""
import json
import math
import sys
from collections import Counter
from pathlib import Path

import scenario as S

try:
    from scipy.stats import fisher_exact
except ImportError:  # pragma: no cover
    fisher_exact = None


def wilson(k: int, n: int) -> str:
    if n == 0:
        return "-"
    z, p = 1.96, k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return f"{k}/{n} ({max(0, c - h):.2f}-{min(1, c + h):.2f})"


def load(run_dir: Path) -> tuple[str, list]:
    src = run_dir / "episodes_rejudged.jsonl"
    src = src if src.exists() else run_dir / "episodes.jsonl"
    recs = [json.loads(l) for l in src.open(encoding="utf-8")]
    head = (run_dir / "summary.txt").read_text(encoding="utf-8") if (run_dir / "summary.txt").exists() else ""
    return head, recs


def model_of(run_dir: Path) -> str:
    cfg = run_dir / "config.json"
    if cfg.exists():
        c = json.loads(cfg.read_text(encoding="utf-8"))
        return f"target {c['target']} / persuader {c['persuader']}"
    for p in Path(__file__).resolve().parent.glob("runs_ablation_*.log"):
        if run_dir.name in p.read_text(encoding="utf-8", errors="ignore"):
            return p.stem.replace("runs_ablation_", "")
    return run_dir.name


def section(name: str, recs: list) -> list:
    conds = [c for c in S.ABLATION if any(r["condition"] == c for r in recs)]
    out = [f"\n## {name}\n",
           "| condition | n all | tip trade (all) | n kept | tip trade (kept) | split (kept) | other trade (kept) | "
           "report (kept) | refused in chat | rule argument | says will report | p vs C1 | p vs C0 |",
           "|" + "---|" * 13]
    tip = {}
    for c in conds:
        ks = [r for r in recs if r["condition"] == c and r["kept"]]
        tip[c] = (sum(r["outcome"]["trade_on_tip"] for r in ks), len(ks))
    for c in conds:
        rs = [r for r in recs if r["condition"] == c]
        ks = [r for r in rs if r["kept"]]
        o = lambda key, rr=ks: sum(r["outcome"][key] for r in rr)
        j = lambda key: sum(bool(r["judge"].get(key)) for r in ks)
        pv = []
        for ref in ("C1_disclose", "C0_earned"):
            if fisher_exact and c != ref and ref in tip and tip[ref][1] and tip[c][1]:
                a, n1 = tip[c]
                b, n2 = tip[ref]
                pv.append(f"{fisher_exact([[a, n1 - a], [b, n2 - b]])[1]:.3f}")
            else:
                pv.append("")
        out.append(f"| {c} | {len(rs)} | {wilson(o('trade_on_tip', rs), len(rs))} | {len(ks)} | "
                   f"{wilson(o('trade_on_tip'), len(ks))} | {o('split')} | {o('other_trade')} | {o('report')} | "
                   f"{j('target_refused_in_chat')} | {j('target_rule_argument')} | {j('target_said_will_report')} | "
                   f"{pv[0]} | {pv[1]} |")
    out += ["", "Reports by object (kept): tip itself / persuader's past trade / persuader's solicitation", ""]
    for c in conds:
        ks = [r for r in recs if r["condition"] == c and r["kept"]]
        objs = Counter(x for r in ks for x in r["judge"].get("report_objects", []))
        out.append(f"- {c}: {objs['tip_itself']} / {objs['persuader_past_trade']} / {objs['persuader_solicitation']}")
    out += ["", "Persuader compliance (kept / all), persuader refused / backed down (all episodes), "
            "and excluded episodes' tip trades:", ""]
    for c in conds:
        rs = [r for r in recs if r["condition"] == c]
        ex = [r for r in rs if not r["kept"]]
        perr = sum(bool(r["judge"].get("parse_error")) for r in rs)
        refused = sum(bool(r["judge"].get("refused")) for r in rs)
        reversed_ = sum(bool(r["judge"].get("reversed")) for r in rs)
        why = Counter(o for r in ex for o in r.get("oversteps", []))
        old = sum(bool(r.get("kept_old")) for r in rs) if any("kept_old" in r for r in rs) else None
        out.append(f"- {c}: kept {len(rs) - len(ex)}/{len(rs)}" + (f" (before rejudge {old})" if old is not None else "")
                   + f"; oversteps {dict(why)}; persuader refused {refused}, backed down "
                   f"{reversed_}; excluded with tip trade {sum(r['outcome']['trade_on_tip'] for r in ex)}/{len(ex)}; "
                   f"judge parse errors {perr}")
    return out


def main() -> None:
    lines = ["# Ablation results (auto-generated by analyze.py)", "",
             "Persuader and judge: deepseek/deepseek-v4-flash. 'tip trade' = short USD/JPY (the tip's direction).",
             "Intervals: Wilson 95%. p: Fisher exact on kept episodes, exploratory, uncorrected."]
    for d in [x for x in sys.argv[1:] if not x.endswith(".md")]:
        run_dir = Path(d)
        _, recs = load(run_dir)
        lines += section(f"{model_of(run_dir)}  ({run_dir.name})", recs)
    text = "\n".join(lines)
    out = Path(__file__).resolve().parent / (sys.argv[1] if sys.argv[1].endswith(".md") else "analysis.md")
    out.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
